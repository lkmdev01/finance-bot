    <p>
        Esta Politica de Privacidade descreve como a InovaFinance trata dados pessoais e dados relacionados ao uso da plataforma web, do painel administrativo,
        das integracoes com terceiros e da assistencia via WhatsApp.
    </p>

    <h2>1. Quem somos</h2>
    <p>
        O InovaFinance e uma plataforma de organizacao financeira com recursos de automacao, assistente conversacional, lembretes, notas, integracoes e painel de acompanhamento.
        Para assuntos de privacidade, contato e suporte, o canal principal e <a href="mailto:contato@inovaforce.com.br">contato@inovaforce.com.br</a>.
    </p>

    <h2>2. Dados que podemos coletar</h2>
    <ul>
        <li>Dados cadastrais, como nome, e-mail, telefone e senha criptografada.</li>
        <li>Dados de autenticacao e conexao, como informacoes de login social, identificadores tecnicos, sessoes e enderecos IP.</li>
        <li>Dados financeiros cadastrados pelo usuario, incluindo transacoes, categorias, metas, orcamentos, lembretes, assinaturas, projecoes e observacoes.</li>
        <li>Conteudo enviado pelo WhatsApp, como mensagens, audios, documentos, imagens, comandos, captions e contexto de conversa.</li>
        <li>Dados de integracoes, como tokens de acesso, identificadores de arquivos e metadados do Google Drive, quando a integracao for ativada pelo proprio usuario.</li>
        <li>Dados de cobranca e assinatura, incluindo status do plano, historico de checkout e eventos do gateway de pagamento.</li>
    </ul>

    <h2>3. Como usamos esses dados</h2>
    <ul>
        <li>Prestar os servicos contratados, incluindo registro, consulta, organizacao e exibicao de dados financeiros.</li>
        <li>Processar comandos enviados no WhatsApp e responder com base no contexto e nos dados do usuario.</li>
        <li>Executar integracoes solicitadas pelo usuario, como salvar arquivos no Google Drive.</li>
        <li>Gerar lembretes, alertas, notificacoes, insights e respostas automatizadas relacionadas ao uso do sistema.</li>
        <li>Prevenir fraudes, abuso, falhas tecnicas e acessos nao autorizados.</li>
        <li>Cumprir obrigacoes legais, regulatórias e contratuais.</li>
        <li>Melhorar a qualidade, estabilidade, seguranca e experiencia do produto.</li>
    </ul>

    <h2>4. Base legal do tratamento</h2>
    <p>
        O tratamento pode ocorrer com fundamento na execucao de contrato, no consentimento do usuario, no cumprimento de obrigacao legal, no exercicio regular de direitos
        e no legitimo interesse para seguranca, suporte, prevencao a fraudes e melhoria do servico, sempre respeitando a legislacao aplicavel.
    </p>

    <h2>5. Compartilhamento de dados</h2>
    <p>Podemos compartilhar dados apenas quando necessario para operar o servico, por exemplo com:</p>
    <ul>
        <li>Provedores de infraestrutura, hospedagem, armazenamento, monitoramento e envio de notificacoes.</li>
        <li>Plataformas de autenticacao e login social, quando escolhidas pelo usuario.</li>
        <li>Provedores de pagamento e faturamento para processamento de assinaturas.</li>
        <li>Servicos conectados pelo proprio usuario, como Google Drive e WhatsApp.</li>
        <li>Autoridades publicas, quando houver obrigacao legal ou ordem valida.</li>
    </ul>
    <p>
        Nao vendemos dados pessoais a terceiros.
    </p>

    <h2>6. Google Drive e arquivos</h2>
    <p>
        Quando o usuario conecta o Google Drive, o InovaFinance utiliza as permissoes concedidas para criar, organizar e acessar apenas os arquivos ou pastas necessarios ao recurso contratado.
        O uso dessa integracao segue os escopos solicitados no consentimento OAuth e a finalidade apresentada ao usuario no momento da conexao.
    </p>

    <h2>7. WhatsApp e conteudo conversacional</h2>
    <p>
        Mensagens, audios, documentos e imagens enviados ao InovaFinance pelo WhatsApp podem ser processados para interpretar comandos, registrar informacoes, salvar arquivos,
        identificar contexto e melhorar a continuidade da conversa. Parte desse conteudo pode ser armazenada para auditoria, seguranca, rastreabilidade e operacao do servico.
    </p>

    <h2>8. Retencao e armazenamento</h2>
    <p>
        Os dados sao mantidos pelo tempo necessario para prestar o servico, atender obrigacoes legais, resolver disputas, garantir seguranca e preservar historico operacional,
        salvo quando o usuario solicitar exclusao e nao houver fundamento legal para retencao adicional.
    </p>

    <h2>9. Seguranca</h2>
    <p>
        Adotamos medidas tecnicas e organizacionais razoaveis para proteger os dados contra acesso nao autorizado, perda, alteracao ou divulgacao indevida.
        Ainda assim, nenhum sistema conectado a internet e absolutamente infalivel, e por isso o usuario tambem deve proteger sua conta e seus dispositivos.
    </p>

    <h2>10. Direitos do titular</h2>
    <p>Observada a legislacao aplicavel, o usuario pode solicitar:</p>
    <ul>
        <li>confirmacao da existencia de tratamento;</li>
        <li>acesso aos dados;</li>
        <li>correcao de dados incompletos, inexatos ou desatualizados;</li>
        <li>anonimizacao, bloqueio ou eliminacao quando cabivel;</li>
        <li>portabilidade, quando aplicavel;</li>
        <li>informacoes sobre compartilhamento;</li>
        <li>revogacao de consentimento, quando essa for a base legal do tratamento.</li>
    </ul>

    <h2>11. Cookies e registros tecnicos</h2>
    <p>
        O site e o painel podem utilizar cookies, sessoes e identificadores tecnicos para autenticacao, seguranca, navegacao, desempenho e experiencia do usuario.
        Alguns recursos podem nao funcionar corretamente se esses mecanismos forem bloqueados.
    </p>

    <h2>12. Alteracoes desta politica</h2>
    <p>
        Esta politica pode ser atualizada periodicamente para refletir evolucoes do produto, exigencias legais ou mudancas operacionais.
        A data da ultima atualizacao sera sempre exibida nesta pagina.
    </p>

